KORGEN = set()
def send_msg(text):
    url = f"https://api.telegram.org/bot{TOKEN}/sendMessage"
    try:
        r = requests.post(url, data={"chat_id": CHAT_ID, "text": text}, timeout=10)
        print("TELEGRAM:", r.text[:200])
    except Exception as e:
        print("Telegram кате:", e)

def jana_ma(text):
    t = text.lower()
    if "бүгін" in t or "сегодня" in t or "кеше" in t or "вчера" in t:
        return True
    if "минут" in t or "сағат" in t or "час" in t:
        return True
    m = re.search(r"(\d+)\s*(күн|дней|дня)", t)
    if m:
        return int(m.group(1)) <= 5
    return False

def tekseru(model, max_baga):
    query = model.replace(" ", "-")
    url = f"https://www.olx.kz/list/q-{query}/"
    headers = {"User-Agent": "Mozilla/5.0"}
    try:
        r = requests.get(url, headers=headers, timeout=15)
        soup = BeautifulSoup(r.text, "html.parser")
        cards = soup.find_all("div", {"data-testid": "l-card"})
        for card in cards[:10]:
            link = card.find("a")
            if not link: continue
            href = link.get("href", "")
            if not href.startswith("http"):
                href = "https://www.olx.kz" + href
            price_tag = card.find("p", {"data-testid": "ad-price"})
            title_tag = card.find("h6")
            if not price_tag or not title_tag: continue
            if not jana_ma(card.get_text(" ", strip=True)): continue
            price_text = "".join(c for c in price_tag.text if c.isdigit())
            if not price_text: continue
            price = int(price_text)
            title = title_tag.text.strip()
            if price <= max_baga and href not in KORGEN:
                KORGEN.add(href)
                send_msg(f"🔥 АРЗАН ТАБЫЛДЫ!\n\n{title}\nБағасы: {price} тг\nЛимит: {max_baga} тг\n\n{href}")
    except Exception as e:
        print(f"Кате {model}: {e}")

